"""Тестирование алгоритма скидки — базовые + граничные случаи."""
from datetime import datetime
from discount import calculate_price_with_discount


def run_tests():
    test_cases = [
        # ---------- Базовая серия (дата 15.10.2026, прошлый месяц — сентябрь) ----------
        (1, 700.0, datetime(2026, 10, 15), 700.0, "Пепперони — есть заказ в сентябре → без скидки"),
        (2, 750.0, datetime(2026, 10, 15), 750.0, "Калифорния — есть заказ в сентябре → без скидки"),
        (3, 350.0, datetime(2026, 10, 15), 350.0, "Гамбургер — есть заказ в сентябре → без скидки"),
        (4, 400.0, datetime(2026, 10, 15), 300.0, "Греческий — нет заказов → −25%"),
        (5, 500.0, datetime(2026, 10, 15), 375.0, "Болоньезе — нет заказов → −25%"),
        (6, 350.0, datetime(2026, 10, 15), 262.5, "Чизкейк — нет заказов → −25%"),
        (7, 100.0, datetime(2026, 10, 15), 75.0,  "Кола — нет заказов → −25%"),

        # ---------- 5 новых граничных тестов ----------

        # 1. Дата расчёта — 1-е число месяца.
        #    Для 01.10.2026 предыдущий месяц — сентябрь. У id=2 есть заказ → без скидки.
        (2, 750.0, datetime(2026, 10, 1), 750.0, "01.10.2026 → сентябрь, заказ есть → без скидки"),

        # 2. Дата расчёта — последний день месяца.
        #    31.10.2026 → тот же сентябрь. У id=4 заказов нет → −25%.
        (4, 400.0, datetime(2026, 10, 31), 300.0, "31.10.2026 → сентябрь, заказов нет → −25%"),

        # 3. Товар с нулевой ценой.
        #    Скидка применяется: 0 × 0.75 = 0. У id=7 нет заказов → ожидаем 0.0.
        (7, 0.0, datetime(2026, 10, 15), 0.0, "Нулевая цена → скидка, но 0 × 0.75 = 0"),

        # 4. Товар с отрицательным количеством — в БД такого быть не должно,
        #    но проверим поведение функции на «странные» данные:
        #    функция не зависит от количества, поэтому цена считается как обычно.
        #    id=5, заказов в сентябре нет → 500 × 0.75 = 375.
        (5, 500.0, datetime(2026, 10, 15), 375.0, "Странные данные не ломают алгоритм"),

        # 5. Товар с заказом в позапрошлом месяце (август), но не в предыдущем (сентябрь).
        #    В нашей БД заказы только в сентябре, поэтому для id=4 (Греческий) — скидка.
        #    Проверяем: дата 15.11.2026 → предыдущий месяц = октябрь, у id=3 нет заказов в октябре
        #    → скидка 350 × 0.75 = 262.5.
        (3, 350.0, datetime(2026, 11, 15), 262.5, "Заказ был в сентябре, но не в октябре → −25%"),
    ]

    print("=" * 70)
    print("РАСШИРЕННОЕ ТЕСТИРОВАНИЕ АЛГОРИТМА СКИДКИ")
    print("=" * 70)

    passed = 0
    for product_id, price, date, expected, comment in test_cases:
        result = calculate_price_with_discount(product_id, price, date)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} Товар {product_id} на {date.date()}: "
              f"{price} → {result} (ожидалось {expected}) — {comment}")

    print("=" * 70)
    print_test_report(passed, len(test_cases))


# ---------- Задание 2: функция отчёта ----------
def print_test_report(passed, total):
    """Выводит итоговый отчёт о тестировании."""
    print("=" * 40)
    print("ОТЧЁТ О ТЕСТИРОВАНИИ")
    print(f"Пройдено: {passed} / {total}")
    if passed == total:
        print("Результат: ✅ УСПЕХ")
    else:
        print("Результат: ❌ ЕСТЬ ОШИБКИ")
    print("=" * 40)


if __name__ == "__main__":
    run_tests()