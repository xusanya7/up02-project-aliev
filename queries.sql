-- Задание 1. Самый дорогой товар
SELECT название, цена FROM Товар ORDER BY цена DESC LIMIT 1;

-- Задание 2. Самый дешёвый товар
SELECT название, цена FROM Товар ORDER BY цена ASC LIMIT 1;

-- Задание 3. Товары одной категории
SELECT название, цена FROM Товар WHERE категория = 'Пицца';

-- Задание 4. Поиск по названию (товары с буквой «о»)
SELECT название, цена FROM Товар WHERE название LIKE '%о%';

-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество FROM Заказ;

-- Задание 6. Заказы конкретного клиента
SELECT * FROM Заказ WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата, Заказ.клиент, Товар.название, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS итого_руб
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS заказов
FROM Заказ
GROUP BY клиент
ORDER BY заказов DESC;

-- Задание 10. Мой запрос
-- Что хочу получить: товары с низким остатком (≤3), отсортированные по цене
SELECT название, цена, количество
FROM Товар
WHERE количество <= 3
ORDER BY цена DESC;